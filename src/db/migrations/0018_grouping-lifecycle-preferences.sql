-- Seed only reviewed or already-used sessions. Unresolved imported labels do
-- not establish a program calendar implicitly.
WITH known_days AS (
  SELECT time_slot_id, weekday FROM grouping_draft_groups
  UNION SELECT time_slot_id, weekday FROM group_recurrences
  UNION SELECT s.id, (r.source_snapshot->'groupingSchedule'->>'weekday')::int
    FROM registrations r JOIN time_slots s
      ON s.program_id = r.program_id
      AND s.id::text = r.source_snapshot->'groupingSchedule'->>'timeSlotId'
    WHERE r.source_snapshot->'groupingSchedule'->>'weekday' ~ '^[0-6]$'
), days AS (
  SELECT time_slot_id, jsonb_agg(weekday ORDER BY weekday) AS weekdays
  FROM known_days GROUP BY time_slot_id
)
UPDATE time_slots s SET allowed_weekdays = days.weekdays
FROM days WHERE days.time_slot_id = s.id AND s.allowed_weekdays = '[]'::jsonb;
